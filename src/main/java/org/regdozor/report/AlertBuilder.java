package org.regdozor.report;

import org.regdozor.match.ObligationRisk;
import org.regdozor.profile.Subject;
import org.regdozor.profile.UserProduct;

import java.util.ArrayList;
import java.util.List;

/**
 * Лепит ТЕКСТ алерта из готовых кусков. Ничего не добывает — всё приходит посчитанным снаружи.
 *
 * Три вопроса клиента — три блока сообщения, каждый из своего источника:
 * «мой ли это товар» (матч по кодам) · «что меняется и когда» (дословная цитата этапов ЦРПТ) ·
 * «чем грозит» (цитаты санкций КоАП под субъекта из профиля). Плюс ссылка и дисклеймер.
 *
 * Отдельным классом, потому что формулировки меняются чаще всего остального, и правка текста не должна
 * означать «лезть в логику дозора». Второй выигрыш — проверяемость: подсовываешь выдуманные списки
 * и смотришь на результат, БЕЗ сети.
 *
 * ⚠️ Свой {@code DISCLAIMER}, а не {@code catalog.AlertFormatter.DISCLAIMER}: каталог идёт под снос,
 * и боевой путь не должен от него зависеть — иначе снос потащит за собой алерт.
 *
 * Текст чужих строк (цитаты КоАП, этапы) вставляется КАК ЕСТЬ, без экранирования — решено осознанно:
 * в источниках таких символов нет. Если однажды появятся, Telegram отвергнет сообщение и напишет об
 * этом в лог — искать вслепую не придётся.
 */
public class AlertBuilder {
    // дисклеймер: бот не юрист, решения клиент принимает сам, сверяясь с первоисточником
    public static final String DISCLAIMER = "Не является юридической консультацией. Сверяйтесь с первоисточником.";

    /**
     * Собирает готовый текст сообщения для Telegram (разметка HTML).
     *
     * @param userProducts    товары, по которым сработал матч — их имена перечисляются через запятую
     * @param stages          этапы внедрения дословно от ЦРПТ; первый несёт дату старта
     * @param obligationRisks подпись нарушения + цитата санкции, по паре на обязанность группы
     * @param subject         правовая форма клиента — её ярлык («ИП») идёт в заголовок блока рисков,
     *                        чтобы было видно, к кому относятся суммы
     * @param url             ссылка на статью-первоисточник
     * @return текст, готовый к отправке через {@code Broadcaster}
     */
    public String glueMessage(List<UserProduct> userProducts, List<String> stages, List<ObligationRisk> obligationRisks,
                              Subject subject, String url) {
        StringBuilder sb = new StringBuilder();   // копим текст кусками
        List<String> names = new ArrayList<>();   // сюда соберём имена товаров для перечисления

        sb.append("🔔 <u><b>Твой товар попал в новый перечень маркировки</b></u>\n\n");

        // цикл ТОЛЬКО собирает имена; склейка — одна операция над готовым списком, поэтому она ниже
        for (UserProduct p : userProducts) {
            names.add(p.productName());
        }
        // join ставит разделитель МЕЖДУ элементами — хвостовой запятой не будет
        String line = String.join(", ", names);

        sb.append("Товары: <b>").append(line).append("</b>\n\n");

        // блок «что меняется»: подпись один раз, маркер — ПЕРЕД каждым этапом.
        // Здесь цикл, а не join: хвостовой перевод строки безвреден, в отличие от хвостовой запятой
        sb.append("📅 Что меняется (ЦРПТ пишет):\n");
        for (String stage : stages) {
            sb.append("• ").append(stage).append("\n");
        }

        // блок «чем грозит»: субъект назван прямо — суммы у ИП и юрлица различаются в разы
        sb.append("\n⚖️ Чем грозит нарушение (КоАП, для ").append(subject.getLabel()).append("):\n");
        for (ObligationRisk o : obligationRisks) {
            // title — подпись НАРУШЕНИЯ («Товар без маркировки»), не обязанности: иначе вышло бы
            // «нарушение за нанесение». Цитата идёт ЦЕЛИКОМ — обрезка исказила бы текст закона
            sb.append("• ").append(o.title()).append(": ").append(o.quote()).append("\n");
        }

        // ссылка голым адресом: Telegram сам сделает её кликабельной, а клиент видит, куда идёт
        sb.append("\n📄 Первоисточник: ").append(url).append("\n");
        sb.append(DISCLAIMER);

        return sb.toString();
    }
}
