package org.regdozor.report;

import org.jsoup.nodes.Document;
import org.regdozor.match.RiskMemo;
import org.regdozor.profile.Profile;
import org.regdozor.profile.UserProduct;

import java.util.List;

/**
 * Контракт «как РАССКАЗАТЬ клиенту про этот документ». Каждый источник рассказывает по-своему.
 *
 * Вторая ось различия между источниками — первую, «как понять, что документ про клиента», уже
 * выражает {@link org.regdozor.match.RelevanceStrategy}. Обе реализации выбираются в одной точке,
 * при сборке в {@code App}, а {@link DozorReporter} остаётся один и про источники не знает ничего.
 *
 * Две реализации, потому что сообщения обязаны быть РАЗНЫМИ, и вот почему:
 * <ul>
 *   <li><b>markirovka</b> — в статье есть раздел «Основные этапы» и коды товаров, поэтому можно
 *       назвать конкретные товары, привести календарь дословно и процитировать санкции КоАП;</li>
 *   <li><b>releasenotes честныйзнак</b> — раздела этапов там НЕТ (извлекатель этапов на такой странице
 *       упал бы), матч идёт по ГРУППЕ, и {@code userProducts} означает не «эти товары затронуты»,
 *       а «релиз вообще про твою группу» — стратегия возвращает весь ассортимент профиля. Приписывать
 *       такому релизу конкретные обязанности и штрафы нельзя: мы не знаем, что в нём написано.</li>
 * </ul>
 *
 */
public interface AlertStrategy {
    /**
     * Составляет текст сообщения по документу, который уже признан относящимся к клиенту.
     *
     * @param doc          разобранная страница — нужна тем, кто читает саму разметку (этапы markirovka);
     *                     простой реализации не нужна, и она её игнорирует
     * @param documentUrl  ссылка на документ — уходит в сообщение первоисточником
     * @param userProducts что вернул матч. ⚠️ Смысл зависит от стратегии релевантности (см. выше)
     * @param riskMemo     памятка на ОДИН прогон дозора ({@link RiskMemo}). Дозор идёт циклом по
     *                     подписчикам, и каждый спрашивает риски по своей группе и форме; памятка
     *                     общая на всех, поэтому текст КоАП (~6.5 МБ) читается один раз на пару
     *                     «группа + субъект», а не по разу на человека. Простой реализации не нужна
     * @return готовый текст сообщения для рассылки
     */
    String composeAlert(Document doc, String documentUrl, Profile profile, List<UserProduct> userProducts, RiskMemo riskMemo);
}
