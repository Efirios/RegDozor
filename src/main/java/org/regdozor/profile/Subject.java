package org.regdozor.profile;

/**
 * Правовая форма клиента (субъект ответственности по КоАП) + её формулировка в тексте статьи.
 *
 * У КоАП штрафы РАЗНЫЕ по субъекту: ИП отвечает КАК ДОЛЖНОСТНОЕ ЛИЦО (примечание к ст. 2.4) —
 * «на должностных лиц»; юрлицо — «на юридических лиц» (у юрлица суммы в разы больше). Профиль хранит
 * ТИП ({@code IP}/{@code LEGAL}), а связка «тип → формулировка КоАП» лежит ЗДЕСЬ, на самих константах —
 * в одном месте.
 *
 * Читается из profile.json по имени константы: {@code "subject": "IP"} → {@code Subject.IP} (Jackson
 * зовёт {@code valueOf}). Дальше {@code getKoapWording()} даёт строку для поиска абзаца штрафа
 * в {@link org.regdozor.match.KoapPenaltyExtractor}.
 *
 * ДВА поля на константе, потому что у субъекта две разные «речи»:
 * <ul>
 *   <li>{@code koapWording} — как он назван В ЗАКОНЕ («на должностных лиц»); это машинный якорь,
 *       по нему режется нужный абзац санкции. Менять нельзя — обязан совпадать с текстом КоАП;</li>
 *   <li>{@code label} — как о нём сказать ЧЕЛОВЕКУ («ИП»); идёт в текст алерта.</li>
 * </ul>
 * ⚠️ Форма {@code label} подогнана под оборот «для {label}» («для ИП», «для юрлица»). В другом
 * обороте («{label} отвечает…») она встанет криво — тогда нужен свой падеж или отдельное поле.
 */
public enum Subject {
    IP("на должностных лиц", "ИП"),        // ИП: по прим. к ст. 2.4 отвечает как должностное лицо
    LEGAL("на юридических лиц", "юрлица");     // юрлицо (ООО и т.п.)

    // формулировка субъекта в тексте КоАП — по ней ищется абзац штрафа (машинный якорь)
    private final String koapWording;
    // как назвать субъекта человеку в алерте: «для ИП» / «для юрлица»
    private final String label;

    // конструктор enum неявно приватный: его зовут ТОЛЬКО константы выше (IP("…"), LEGAL("…"))
    Subject(String koapWording, String label) {
        this.koapWording = koapWording;   // сохраняем формулировку на константе
        this.label = label;               // и человеческий ярлык рядом с ней
    }

    // отдаёт формулировку КоАП для этого субъекта (для поиска абзаца санкции)
    public String getKoapWording() {
        return koapWording;
    }

    // отдаёт человеческий ярлык для текста алерта
    public String getLabel() {
        return label;
    }
}
