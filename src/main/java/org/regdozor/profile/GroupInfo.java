package org.regdozor.profile;

import java.util.List;

/**
 * Одна строка справочника «товарная группа → где её искать и какими словами она называется».
 *
 * Существует ради ОНБОРДИНГА. {@link Profile} состоит из четырёх частей, но человек может назвать
 * только две: правовую форму и свои товары с кодами. Остальные две спросить нельзя —
 * {@code section} это кусок URL чужого сайта, а {@code groupTerms} набор формулировок для матча.
 * Поэтому их не спрашивают, а ВЫВОДЯТ из группы, которую человек назвал («одежда»).
 *
 * Родная сестра {@code obligations.json}: маленький выверенный справочник, который заполняет человек,
 * а не бот. Разница в вопросе: там «группа + обязанность → статья КоАП», здесь «группа → раздел и слова».
 *
 * ⚠️ Типы компонентов повторяют {@link Profile} НАРОЧНО — оба списки. Тогда при онбординге значения
 * ложатся в профиль напрямую, без преобразований.
 *
 * @param group      название группы («одежда») — ключ справочника. ⚠️ Должно совпадать с полем
 *                   {@code group} в obligations.json и в {@link UserProduct}: по нему ищется статья КоАП
 * @param section    разделы markirovka, где публикуются статьи этой группы («shoes-and-clothes»).
 *                   По ним {@code MarkirovkaFeedMonitor} отбирает ссылки из общей ленты
 * @param groupTerms формулировки, по которым группа узнаётся В ТЕКСТЕ — для источников без кодов
 *                   (релизы честныйзнака). ⚠️ Нужны В РАЗНЫХ ПАДЕЖАХ: матч идёт ПОДСТРОКОЙ, а не по
 *                   словарю, и «лёгкая промышленность» не найдётся во фразе «перечня товаров лёгкой
 *                   промышленности». Каждый термин — ОТДЕЛЬНЫЙ элемент списка; склей их в одну строку
 *                   через запятую — бот будет искать в статье эту строку целиком и не найдёт НИКОГДА
 */
public record GroupInfo(String group, List<String> section, List<String> groupTerms) {
}
