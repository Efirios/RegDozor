package org.regdozor.profile;

/**
 * Один товар пользователя: как он его называет + два кода, по которым узнаём его в перечнях.
 *
 * Заменяет «товарную карточку» каталога ({@code catalog.Product}): там рядом с кодами руками
 * держали обязанности, даты и штрафы — ручная курация, которая не масштабируется. Здесь только то,
 * что реально знает человек про СВОЙ товар. Всё остальное берётся из живых источников: обязанности —
 * от группы через таблицу, риск — из текста КоАП, дата — из статьи markirovka.
 *
 * ⚠️ ДВА кода, а не один — это не избыточность. Четырёхзначный ТН ВЭД неоднозначен: позиция 6104
 * накрывает и юбки клиента (волна 2), и спецодежду/СИЗ (волна 4). Матч требует НАЙТИ ОБА кода, и
 * второй отсекает чужую волну. Проверено фактом на статье с 01.03.2026: там «6104» есть, а ОКПД2
 * «14.13.14» — нет, и алерт правильно не сработал.
 *
 * ⚠️ Коды — СТРОКИ, не числа: «14.39.10» числом не является, а у ТН ВЭД бывают ведущие нули и пробелы
 * («6109 90 200 0»).
 *
 * @param productName как товар называет сам клиент («Майка женская») — попадёт в текст алерта
 * @param tnved       код ТН ВЭД («6109»). Иерархичен: 4/6/10 знаков, глубина важна
 * @param okpd2       код ОКПД2 («14.14.30»). ⚠️ НЕ сверены с Нацкаталогом ЧЗ — подбор по классификатору,
 *                    сходится с волнами, но перед выпуском продукта подтвердить у клиента
 */
public record UserProduct(String productName, String tnved, String okpd2) {
}
