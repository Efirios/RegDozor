package org.regdozor.profile;

import java.util.List;

/**
 * Профиль пользователя (данные о НЁМ, в отличие от каталога товаров).
 * Это единственное, что задаёт человек. Позже дорастёт: правовая форма (ИП/ООО — от неё зависит штраф),
 * коды его товаров.
 *
 * @param groupTerms термины группы (напр. «лёгкая промышленность», «одежда и бельё») — матчинг нормализует их
 *                   (регистр, ё/е). По ним узнаём релевантные релизы ЦРПТ, которые описывают изменения
 *                   НАЗВАНИЯМИ групп, а не кодами.
 * @param section    разделы markirovka.ru/community/, которые сторожим для этого пользователя
 *                   (напр. «shoes-and-clothes»). Список: продавец может торговать в нескольких группах.
 *                   Это структурный сигнал группы из URL — надёжнее текстового матча по groupTerms.
 */
public record Profile(List<String> groupTerms, List<String> section) {
}
