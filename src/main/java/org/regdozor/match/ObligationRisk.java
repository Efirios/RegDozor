package org.regdozor.match;

/**
 * Готовая пара для алерта: одна обязанность и цитата того, чем грозит её нарушение.
 *
 * Из таких пар состоит ответ {@link KoapRisk#risksForGroup}: у группы обязанностей несколько,
 * и у каждой свой штраф. В сообщении клиенту превращается в строку вида
 * «<b>Нанесение</b>: влечет наложение … от пяти тысяч до десяти тысяч рублей с конфискацией …».
 *
 * @param obligation имя обязанности, как оно записано в obligations.json («нанесение» / «ГИС МТ»)
 * @param quote      ДОСЛОВНАЯ цитата санкции из живой редакции КоАП (суммы словами, не число):
 *                   мы не пересказываем закон и не считаем штраф — приводим текст как есть
 */
public record ObligationRisk(String obligation, String quote) {
}
