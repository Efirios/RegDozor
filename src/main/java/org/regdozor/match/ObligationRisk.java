package org.regdozor.match;

/**
 * Готовая пара для алерта: подпись нарушения и цитата того, чем оно грозит.
 *
 * Из таких пар состоит ответ {@link KoapRisk#risksForGroup}: у группы обязанностей несколько,
 * и у каждой свой штраф. В сообщении клиенту превращается в строку вида
 * «Товар без маркировки: влечет наложение … от пяти тысяч до десяти тысяч рублей с конфискацией …».
 *
 * Смысл пары в том, что её половины родом из РАЗНЫХ миров: {@code title} — наша формулировка из
 * obligations.json, {@code quote} — чужой текст закона. По отдельности они бесполезны: цитата без
 * подписи непонятна («это про что?»), подпись без цитаты голословна.
 *
 * Не хранится нигде и живёт секунды: рождается в {@code risksForGroup}, умирает после того, как
 * {@code AlertBuilder} собрал текст. Это значение по дороге, а не сущность предметной области.
 *
 * @param title подпись НАРУШЕНИЯ для человека («Товар без маркировки») — это {@code violationLabel}
 *              из obligations.json, а НЕ машинный ключ {@code obligation} («нанесение»): наружу уходит
 *              только человеческая формулировка
 * @param quote ДОСЛОВНАЯ цитата санкции из живой редакции КоАП (суммы словами, не число):
 *              мы не пересказываем закон и не считаем штраф — приводим текст как есть
 */
public record ObligationRisk(String title, String quote) {
}
