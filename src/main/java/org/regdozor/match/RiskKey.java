package org.regdozor.match;

import org.regdozor.profile.Subject;

/**
 * Ключ для {@link RiskMemo}: пара «товарная группа + правовая форма».
 *
 * ⚠️ ИМЕННО ПАРА, а не одна группа. {@link KoapRisk#risksForGroup} даёт РАЗНЫЕ ответы для ИП
 * и юрлица: субъект выбирает, какой абзац санкции цитировать («на должностных лиц» против
 * «на юридических лиц»), а суммы там отличаются в разы. Запоминай мы ответ по одной группе —
 * юрлицо получило бы ИП-шные суммы, то есть ровно ту дыру, ради которой затевалась
 * мультипользовательность.
 *
 * {@code record}, потому что это КЛЮЧ КАРТЫ: {@code equals} и {@code hashCode} генерируются
 * автоматически по всем компонентам, и два разных объекта с одинаковым содержимым для карты
 * одинаковы. У обычного класса без этих методов сравнение шло бы по ссылке, повторный спрос
 * никогда не нашёл бы прежний ответ, и память «работала» бы, ни разу не сработав.
 * Тот же приём и по той же причине, что в {@link ObligationKey}.
 *
 * @param group   товарная группа («одежда») — как в obligations.json
 * @param subject правовая форма клиента из профиля
 */
public record RiskKey(String group, Subject subject) {
}
