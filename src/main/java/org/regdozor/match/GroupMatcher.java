package org.regdozor.match;

import org.regdozor.profile.Profile;

/**
 * Сигнал релевантности по НАЗВАНИЮ группы (для релизов ЦРПТ, где нет кодов ТН ВЭД).
 * concernsGroup: нормализует текст и термины (toLowerCase + ё→е против ловушек регистра и буквы ё)
 * и возвращает true, если найден ЛЮБОЙ термин группы (в отличие от RelevanceChecker: там «найдены ВСЕ коды»).
 * ВАЖНО: подавать сюда ТОЛЬКО тело статьи (иначе меню/шапка с названиями всех групп → ложные срабатывания).
 */
public class GroupMatcher {
    /**
     * Относится ли текст к товарной группе пользователя?
     * Правило: достаточно НАЙТИ ЛЮБОЙ из терминов группы (в отличие от RelevanceChecker,
     * где требуются ВСЕ коды сразу). Причина: группу называют по-разному — «лёгкая промышленность»,
     * «одежда и бельё», «одежды и белья» — и любое из этих названий означает, что нас касается.
     *
     * @param text    ТОЛЬКО тело статьи! Если подать всю страницу, в неё попадут меню и шапка,
     *                где перечислены ВСЕ товарные группы — и совпадёт что угодно (ложное срабатывание).
     * @param profile профиль пользователя с терминами его группы
     * @return true, если найден хотя бы один термин
     */
    public boolean concernsGroup(String text, Profile profile) {
        // Нормализуем ОБЕ стороны сравнения: регистр (Одежда/одежда) и букву ё (бельё/белье),
        // иначе один и тот же термин не совпал бы из-за написания.
        String normalText = text.toLowerCase().replace('ё', 'е');

        for (String term : profile.groupTerms()) {
            String normTerm = term.toLowerCase().replace('ё', 'е');

            if (normalText.contains(normTerm)) {
                return true;
            }
        }

        return false;
    }
}
