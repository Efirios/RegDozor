package org.regdozor.match;

import org.regdozor.profile.Subject;

import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Памятка на ОДИН прогон дозора: не считать одно и то же дважды, пока обрабатывается один документ.
 *
 * Зачем. После перехода на профили по подписчикам дозор идёт ЦИКЛОМ ПО ЛЮДЯМ, и каждый спрашивает
 * риски по своей группе и своей форме. А {@link KoapRisk#risksForGroup} внутри читает ВЕСЬ текст КоАП —
 * два сетевых запроса и ~6.5 МБ. Без памятки два подписчика-ИП с одеждой скачали бы кодекс дважды
 * подряд ради одинакового ответа; десять подписчиков — десять раз на каждую статью.
 *
 * ⚠️ ЭТО НЕ КЕШ, от которого мы сознательно отказались в {@code ArticleTextFetcher}. Там речь шла
 * о долгоживущей скрытой памяти: непонятно, когда протухает и что делать при правке страницы. Здесь
 * объект создаётся ПУСТЫМ на каждый документ и умирает вместе с обработкой — протухнуть не может
 * по построению, потому что внутри одного прогона текст КоАП не меняется.
 *
 * Кто создаёт: {@code DozorReporter} в начале обработки документа, по одной штуке, и передаёт
 * стратегии сообщения. Все подписчики спрашивают одну и ту же памятку — отсюда и экономия.
 *
 * Проверено подставным калькулятором (без сети): три спроса одной пары → калькулятор позван ОДИН раз
 * и все три раза вернулся один и тот же объект; спрос с другим субъектом → позван второй раз и ответ
 * другой; повтор обеих пар → счётчик не вырос.
 */
public class RiskMemo {
    // кто реально считает: дорогой вызов с походом в сеть за текстом кодекса
    private final KoapRisk koapRisk;
    // что уже посчитано в этом прогоне. Обычный HashMap, а НЕ LinkedHashMap: по карте мы не ходим,
    // только обращаемся по ключу, поэтому порядок не нужен (в отличие от таблицы обязанностей,
    // где порядок задаёт очерёдность обязанностей в алерте).
    // Создаётся пустой прямо здесь: памятка одноразовая и всегда начинает с чистого листа.
    private final Map<RiskKey, List<ObligationRisk>> koapRisks = new HashMap<>();

    public RiskMemo(KoapRisk koapRisk) {
        if (koapRisk == null) {
            throw new IllegalArgumentException("koapRisk не должен быть null");
        }
        this.koapRisk = koapRisk;
    }

    /**
     * Отдаёт риски по группе и субъекту, считая их не более одного раза за прогон.
     *
     * @param group   товарная группа совпавшего товара
     * @param subject правовая форма подписчика — от неё зависит, какой абзац санкции процитирован
     * @return то же, что вернул бы {@link KoapRisk#risksForGroup}; при повторном спросе — ТОТ ЖЕ объект
     */
    public List<ObligationRisk> risksFor(String group, Subject subject) {
        // ключ составляем ОДИН раз и используем оба раза — и для поиска, и для сохранения
        RiskKey riskKey = new RiskKey(group, subject);
        // ⚠️ get принимает Object, а не RiskKey: тип ключа компилятор здесь НЕ проверяет.
        // Ошибись мы типом ключа карты — код бы собрался, а поиск промахивался бы всегда.
        List<ObligationRisk> risks = koapRisks.get(riskKey);

        // null означает «такую пару ещё не спрашивали» — пустого списка тут не бывает:
        // KoapRisk при отсутствии группы в таблице ПАДАЕТ, а не возвращает пустоту
        if (risks != null) {
            return risks;   // готово — в сеть не идём
        }

        // первый спрос этой пары: вот здесь и происходят два запроса и ~6.5 МБ
        risks = koapRisk.risksForGroup(group, subject);
        koapRisks.put(riskKey, risks);
        return risks;
    }
}
