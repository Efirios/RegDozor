package org.regdozor.match;

/**
 * Находит статью КоАП по номеру и отдаёт её ПРОВЕРЕННЫЙ текст.
 *
 * Вход: полный HTML-текст КоАП (его отдаёт {@link org.regdozor.pravo.PravoEbpiTextFetcher} —
 * несколько мегабайт, со всеми вклеенными поправками) + номер статьи ДВУМЯ частями: базовый номер
 * ("15.12") и надстрочник (0 — надстрочника нет, 1 — ст. 15.12¹, 2 — ст. 15.12²). Выход: текст
 * ровно этой одной статьи.
 *
 * Зачем номер двумя частями. В тексте КоАП надстрочный номер лежит НЕ как "15.12.1", а как разметка:
 * {@code Статья 15.12<span class="W9">1</span>}. Из-за этого простые проверки врут МОЛЧА:
 * {@code contains("15.12.1")} не найдёт ничего (такого литерала в тексте нет), а
 * {@code contains("15.12")} склеит ТРИ разные статьи (15.12, 15.12¹, 15.12²) с разными штрафами.
 * Поэтому база и надстрочник разведены, а различитель — что стоит СРАЗУ после номера: точка → базовая
 * статья; {@code <span class="W9">} → надстрочная.
 *
 * Устроен как «луковица» из трёх методов, каждый — одна работа:
 * <pre>
 *   locateArticle (наружу)  — вырезать статью + проверить канарейкой, отдать проверенный текст;
 *     └ cutArticle          — вырезать тело статьи (от заголовка до следующего заголовка);
 *         └ findArticleStart — найти позицию начала нужной статьи.
 * </pre>
 * Снаружи виден только {@link #locateArticle}; два других — приватные помощники.
 *
 * Место в цепочке: [таблица «обязанность → статья»] даёт номер → ЭТОТ класс достаёт текст статьи →
 * [следующий шаг] цитирует из него абзац про должностных лиц. Сам НЕ качает текст (это
 * PravoEbpiTextFetcher) и НЕ решает, какую статью искать (это таблица).
 *
 * ⚠️ Работает по СЫРОМУ HTML (со span'ами и тегами), а не по очищенному тексту: очистка
 * ({@code doc.text()}) склеила бы надстрочник в "15.121", и различить статьи стало бы нельзя.
 */
public class KoapArticleLocator {
    /**
     * Находит позицию, с которой начинается нужная статья, различая базовую и надстрочную.
     *
     * Собирает «якорь» — точную строку-заголовок — и ищет её первое вхождение. Для надстрочника 0
     * якорь = {@code "Статья 15.12."}: точка отсекает 15.12¹/15.12² (у них после номера идёт "<").
     * Для надстрочника N якорь = {@code "Статья 15.12<span class=\"W9\">N</span>"} — он уникален.
     *
     * ⚠️ Не нашлось ({@code indexOf} вернул -1) → НЕ возвращаем -1 молча, а падаем: тихий промах —
     *    худший отказ дозорного. Текст исключения несёт сам якорь, чтобы сторож понял, что сломалось.
     *
     * @param koapHtml    полный HTML-текст КоАП
     * @param baseNumber  базовый номер статьи, напр. "15.12"
     * @param superscript надстрочник: 0 (нет), 1 (¹), 2 (²)
     * @return позиция (индекс символа), с которой начинается заголовок статьи
     * @throws IllegalStateException если статья с таким якорем в тексте не найдена
     */
    private int findArticleStart(String koapHtml, String baseNumber, int superscript) {
        String anchor;

        if (superscript == 0) {
            anchor = "Статья " + baseNumber + ".";
        } else {
            anchor = "Статья " + baseNumber + "<span class=\"W9\">" + superscript + "</span>";
        }

        int start = koapHtml.indexOf(anchor);

        if (start == -1) {
            throw new IllegalStateException(anchor + " не нашлась");
        }

        return start;
    }

    /**
     * Вырезает ТЕЛО статьи — от её начала до начала следующей статьи.
     *
     * Берёт позицию начала у {@link #findArticleStart}, затем ищет следующий заголовок (маркер
     * {@code <p class="H"}) начиная ОТ этой позиции — так проскакивает заголовок текущей статьи
     * (его тег стоит чуть раньше) и попадает на соседнюю. Возвращает кусок между ними.
     *
     * ⚠️ Режет ЛЮБУЮ статью, без проверки содержимого — это забота {@link #locateArticle}. Тело
     *    возвращается как СЫРОЙ HTML (с тегами): дальше по нему удобнее искать абзацы, чистка — при
     *    цитировании.
     * ⚠️ Край: если статья ПОСЛЕДНЯЯ, следующего заголовка нет ({@code indexOf} = -1) → режем до конца текста.
     *
     * @return текст статьи в HTML (без проверки, что это именно статья о маркировке)
     */
    private String cutArticle(String koapHtml, String baseNumber, int superscript) {
        int start = findArticleStart(koapHtml, baseNumber, superscript);
        int end = koapHtml.indexOf("<p class=\"H\"", start);

        if (end == -1) {
            return koapHtml.substring(start, koapHtml.length());
        } else {
            return koapHtml.substring(start, end);
        }
    }

    /**
     * Отдаёт ПРОВЕРЕННЫЙ текст статьи о маркировке — единственная дверь наружу.
     *
     * Вырезает статью ({@link #cutArticle}) и прогоняет КАНАРЕЙКУ: настоящая маркировочная статья
     * обязана содержать и "маркировк", и "должностных лиц". Нет хотя бы одного — значит разметку КоАП
     * поменяли или вырезали не то; вместо тихой выдачи мусора падаем с внятным сообщением для сторожа.
     *
     * ⚠️ Только ОБНАРУЖИВАЕТ поломку (throw). Кто поймает сигнал и известит РАЗРАБОТЧИКА (не клиента) —
     *    забота верхнего слоя.
     *
     * @param koapHtml    полный HTML-текст КоАП
     * @param baseNumber  базовый номер статьи, напр. "15.12"
     * @param superscript надстрочник: 0 (нет), 1 (¹), 2 (²)
     * @return текст статьи в HTML, прошедший проверку содержимого
     * @throws IllegalStateException если статья не найдена или не похожа на статью о маркировке
     */
    public String locateArticle(String koapHtml, String baseNumber, int superscript) {
        String article = cutArticle(koapHtml, baseNumber, superscript);

        if (!(article.contains("маркировк") && article.contains("должностных лиц"))) {
            throw new IllegalStateException("Нет совпадений по названиям. Статья " + baseNumber + "^" +
                    superscript + " могла измениться");
        }

        return article;
    }
}
