package org.regdozor.operator;

import org.jsoup.nodes.Document;
import org.jsoup.nodes.Element;
import org.jsoup.select.Elements;

import java.util.ArrayList;
import java.util.List;

/**
 * Достаёт из статьи markirovka раздел «Основные этапы маркировки» — календарь внедрения, дословно.
 *
 * Вход: разобранная страница ({@link Document} — качает и парсит кто-то другой). Выход: список строк,
 * по одной на этап, было → стало:
 * <pre>
 *   было:  &lt;p&gt;&lt;b&gt;С&amp;nbsp;1&amp;nbsp;марта 2026 года&lt;/b&gt;&amp;nbsp;— старт обязательной маркировки…&lt;/p&gt;
 *   стало: "С 1 марта 2026 года — старт обязательной маркировки для новых товаров…"
 * </pre>
 *
 * 🎁 ПЕРВЫЙ элемент — ДАТА СТАРТА словами ЦРПТ. Поэтому отдельный парсер даты НЕ нужен: вытащив блок,
 * мы получаем весь календарь разом (на проверенной статье — 5 этапов: старт 01.03.2026, таможня 01.07,
 * импорт по 01.08, запрет продажи остатков с 01.08, коды на остатки по 01.12). Одним парсером меньше —
 * одним местом для бесшумного промаха меньше.
 *
 * Зачем цитата, а не наш пересказ: ЦРПТ — ярус 2 источников, его текст цитировать МОЖНО с атрибуцией,
 * и это ноль риска исказить. Пересказывать пять этапов своими словами = делать вывод за клиента.
 *
 * Чего НЕ делает: не качает и не парсит страницу; не разбирает дату в число (её цитируют, а не считают);
 * не проверяет коды ({@code RelevanceChecker}); не решает, кому слать ({@code DozorReporter}).
 *
 * ⚠️ MARKIROVKA-СПЕЦИФИЧЕН: знает про {@code h3} «Основные этапы». У релизов честныйзнак такого раздела
 * нет — отсюда отдельный класс, как {@link CrptReleaseExtractor} и {@link MarkirovkaReleaseExtractor}.
 *
 * ⚠️ Разметка блока (проверено на живой статье): заголовок — {@code <h3>}, каждый этап — отдельный
 * {@code <p>} (дата внутри обёрнута в {@code <b>}), СОСЕДИ заголовка, а не потомки. После этапов идёт
 * сноска в {@code <blockquote>} и следующий {@code <h3>} — они и служат границей.
 */
public class MarkirovkaStagesExtractor{
    /**
     * Отдаёт этапы внедрения маркировки из статьи, по строке на этап.
     *
     * @param doc разобранная страница статьи markirovka
     * @return этапы дословно; первый — дата старта
     * @throws IllegalStateException если раздела «Основные этапы» на странице нет ИЛИ он найден,
     *                               но абзацев за ним не оказалось (вёрстку изменили) — канарейка:
     *                               пустой список отдавать нельзя, это молчание, а не сигнал
     */
    public List<String> extractStages(Document doc) {
        // все заголовки h3 на странице — их несколько (наш раздел, «Как промаркировать остатки?» и т.д.)
        Elements elements = doc.select("h3");
        // сюда положим найденный заголовок; null = «ещё не нашли» (по нему потом и проверим успех)
        Element e = null;
        // корзина под этапы: ArrayList, потому что наполняем в цикле (List.of() неизменяем — add упал бы)
        List<String> stages = new ArrayList<>();
        for (Element heading : elements) {
            // contains, а не equals: в разметке после названия лишний пробел — строгое сравнение промахнулось бы МОЛЧА
            if (heading.text().contains("Основные этапы")) {
                e = heading;
                break;   // нашли — запомнили и хватит искать; чужие заголовки молча пропускаем (это не ошибка)
            }
        }

        // перебрали всех, своего нет → канарейка. ⚠️ Проверка стоит ДО сбора: у null-ссылки метод не вызвать (NPE)
        if (e == null) {
            throw new IllegalStateException("Нет совпадений заголовка. Раздел переименовали или вёрстку поменяли");
        }

        // все элементы ПОСЛЕ заголовка на том же уровне: абзацы этапов, потом сноска, потом следующий заголовок
        Elements nextAdjacentElement = e.nextElementSiblings();
        for (Element sibling : nextAdjacentElement) {
            // граница блока: первый не-абзац (blockquote со сноской или новый h3) — стоп.
            // equals, а не contains: "span".contains("p") тоже истинно, и мы собрали бы мусор.
            // Считаем по ПРИЗНАКУ, а не «взять 5 абзацев» — в другой статье этапов будет другое число
            if (!(sibling.tagName().equals("p"))) {
                break;
            }
            stages.add(sibling.text());   // .text() снимает теги И нормализует &nbsp; в обычные пробелы
        }

        // заголовок есть, а абзацев ноль → вёрстку абзацев изменили. isEmpty(), а не == null: корзина создана выше
        if (stages.isEmpty()) {
            throw new IllegalStateException("Раздел найден, а абзацев за ним нет");
        }

        return stages;
    }

}
