package org.regdozor.telegram;

/**
 * Шаг анкеты онбординга: КАКОЙ ОТВЕТ бот сейчас ждёт от человека — и какой вопрос для этого задаёт.
 *
 * В Telegram диалог нельзя написать как в консоли: там программа стоит и ждёт ввода, а тут каждое
 * сообщение приходит ОТДЕЛЬНЫМ событием. Пришло «6109» — понять, это код ТН ВЭД или название товара,
 * можно только зная, что мы у этого человека спрашивали. Отсюда и шаг: он хранится между сообщениями
 * (в {@link OnboardingState}) и служит ответом на вопрос «что означает пришедший текст».
 *
 * Вопрос лежит НА САМОЙ КОНСТАНТЕ — тот же приём, что в {@link org.regdozor.profile.Subject}, где
 * на константе висят формулировка КоАП и человеческий ярлык. Так все формулировки собраны в одном
 * месте, а диалог задаёт их единообразно, не разбирая шаги руками.
 *
 * ⚠️ Константы «готово» здесь НЕТ намеренно: закончив анкету, мы записываем профиль и УДАЛЯЕМ файл
 * состояния. Отсутствие файла и означает «разговор не идёт». Отдельный шаг «завершено» пришлось бы
 * хранить вечно и отличать от отсутствия — лишняя сущность.
 *
 * ⚠️ В json шаг пишется ИМЕНЕМ константы ({@code "WAITING_FOR_THE_OKPD2"}), Jackson читает его через
 * {@code valueOf}. Значит переименование константы ломает уже сохранённые незаконченные анкеты.
 */
public enum OnboardingStep {
    WAITING_FOR_THE_LEGAL_FORM("Вы ИП или юрлицо?"),
    WAITING_FOR_THE_GROUP_NAME("Какую товарную группу продаёте?"),
    WAITING_FOR_THE_PRODUCT_NAME("Как называется товар?"),
    WAITING_FOR_THE_TNVED("Введите код ТН ВЭД"),
    WAITING_FOR_THE_OKPD2("Введите код ОКПД2"),
    WAITING_FOR_THE_ANSWER("Добавить ещё товар или хватит");

    private final String questionWording;

    OnboardingStep(String questionWording) {
        this.questionWording = questionWording;
    }

    public String getQuestionWording() {
        return questionWording;
    }
}
