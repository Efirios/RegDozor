package org.regdozor.telegram;

/**
 * Сообщение внутри {@link Update}. В настоящем JSON у него много полей (message_id, from, date…),
 * нам нужны два: КТО написал и ЧТО написал. Остальное Jackson отбросит.
 *
 * ⚠️ Имена компонентов обязаны совпадать с полями JSON Telegram ТОЧЬ-В-ТОЧЬ. При опечатке Jackson
 * не упадёт (в проекте стоит {@code FAIL_ON_UNKNOWN_PROPERTIES=false}) — молча оставит {@code null}.
 *
 * @param chat чат, откуда пришло сообщение — из него берём id, чтобы знать, кому отвечать
 * @param text текст сообщения. ⚠️ БЫВАЕТ {@code null} ПО-ЧЕСТНОМУ, и это не поломка: Telegram присылает
 *             сообщение без текста, когда прилетел стикер, картинка, файл или человек вошёл в чат —
 *             тогда поля {@code text} в JSON просто нет. Всякий, кто это читает, обязан проверить
 *             на {@code null}, иначе первый же стикер от клиента уронит приёмник
 */
public record Message(Chat chat, String text) {
}
